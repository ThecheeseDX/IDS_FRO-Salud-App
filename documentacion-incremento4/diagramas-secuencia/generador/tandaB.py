# Dos actores. El profesional (V_Bonos_Contingencia) registra el bono provisorio
# y en su rol van las 4 excepciones de la ficha (todas ocurren al abrir y al
# registrar). El administrador (V_Contingencia_Bonos) fuerza el modo y
# regulariza el bono con el financiador; su registro es igual al del profesional.
# C_Gestor_Contingencia (contingenciaService) decide si la contingencia esta activa.
def cu72_estado(bitacora, ret_bitacora, ret_cont, modo='modo 0, ventana 30', ret_modo='return (modo automatico, 30 min)'):
    return [f'{API} -> {CONT}: estado_contingencia()',
            *leer_de(CONT, 'leer_parametros(MODO_CONTINGENCIA, VENTANA_MINUTOS)', 'Parametro_Global', 'clave, valor',
                     modo, ret_modo),
            *leer_de(CONT, 'leer_ultima_integracion_del_financiador(ventana)', 'Bitacora_Auditoria',
                     'momento_evento, accion, datos_adicionales', bitacora, ret_bitacora),
            f'{CONT} ->> {CONT}: evaluar_falla(LIMITE_REINTENTOS o sin respuesta)',
            f'{CONT} --> {API}: {ret_cont}']

